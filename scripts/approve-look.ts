// Records skye's current look as the approved one. Bundles the core, as the working tree has it, into one minified
// module, test/reference/skye-approved.js, with its type declarations from the same snapshot beside it. The look
// gate draws it beside skye in every case (test/look/), so a change to the image fails the gate until this runs
// again: run it only for a change whose look the owner has approved (CONTRIBUTING.md, Look preservation), and commit
// both files in the commit that makes that change.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "tsdown";
import { readableShaders, writeShaders } from "./shaders.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "test/reference/skye-approved");

const HEADER =
  "// skye's core as of the look the owner last approved. Generated by `bun run look:approve` " +
  "(scripts/approve-look.ts); do not edit.\n";

// The readable names draw the same image, but the module would then not be what ships.
if (readableShaders()) throw new Error("approve-look: unset SKYE_READABLE_SHADERS first");
writeShaders();
const dir = mkdtempSync(join(tmpdir(), "skye-approved-"));
try {
  await build({
    config: false,
    entry: { approved: join(ROOT, "src/index.ts") },
    outDir: dir,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    dts: { sourcemap: false },
    sourcemap: false,
    logLevel: "warn",
  });
  writeFileSync(`${OUT}.js`, HEADER + readFileSync(join(dir, "approved.js"), "utf8"));
  writeFileSync(`${OUT}.d.ts`, HEADER + readFileSync(join(dir, "approved.d.ts"), "utf8"));
} finally {
  rmSync(dir, { recursive: true, force: true });
}
